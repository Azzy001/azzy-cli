# boto3 paginators
# paginators help handle large sets of AWS API responses by automatically iterating 
# through pages of results instead of retrieving everything at once. 
# this is useful because AWS services often limit the number of results 
# returned in a single API call.
#
# Why Use Paginators?
#   * AWS API responses are paginated when data is large.
#   * Paginators automate handling multiple pages of results.
#   * Avoids hitting API limits by making multiple requests under the hood.
